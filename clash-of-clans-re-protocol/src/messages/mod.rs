impl std::fmt::Display for MessageId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{} ({})", self.name(), *self as u16)
    }
}

pub fn get_all_message_ids() -> HashMap<u16, &'static str> {
    let mut map = HashMap::new();
    for id in 10100..=26008 {
        if let Some(msg) = MessageId::from_u16(id) {
            map.insert(id, msg.name());
        }
    }
    map
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_message_id_conversion() {
        assert_eq!(MessageId::from_u16(10101), Some(MessageId::Login));
        assert_eq!(MessageId::from_u16(20104), Some(MessageId::LoginOk));
        assert_eq!(MessageId::from_u16(9999), None);
    }

    #[test]
    fn test_direction() {
        assert!(MessageId::Login.is_client_to_server());
        assert!(MessageId::LoginOk.is_server_to_client());
    }

    #[test]
    fn test_names() {
        assert_eq!(MessageId::Login.name(), "Login");
        assert_eq!(MessageId::LoginOk.name(), "LoginOk");
    }
}